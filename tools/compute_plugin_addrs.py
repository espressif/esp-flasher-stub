"""
Compute a plugin's load addresses from the base stub ELF and emit a linker
script fragment defining PLUGIN_TEXT_ADDR and PLUGIN_BSS_ADDR.  The fragment
also PROVIDEs every global function and object of the base stub, so a plugin
can call the base functions marked STUB_EXPORT directly.

A plugin is loaded immediately after the base stub.  Multiple plugins stack:
pass each preceding plugin's ELF via --after, in load order, so this plugin is
placed after the end of their .text, and after the end of their .bss and .data.

    # First plugin: right after the base stub
    compute_plugin_addrs.py base.elf nand_plugin_addrs.ld

    # Second plugin: stacked after the first
    compute_plugin_addrs.py base.elf spi_ram_plugin_addrs.ld --after nand_plugin.elf

The generated fragment is pulled in by the plugin's linker script via -T and
supplies the MEMORY origins, replacing the old configure-time -Wl,--defsym.
"""

import argparse
import sys

try:
    from elftools.elf.elffile import ELFFile
except ImportError:
    raise SystemExit('pyelftools not found. Install with: pip install pyelftools')


def align_up(value, alignment):
    return (value + alignment - 1) & ~(alignment - 1)


def _end(elf, *names):
    """End address of the last of the named sections, 0 if there are none.

    The linker may move a section up to its alignment, so this uses the linked
    addresses and not the sizes.
    """
    secs = [elf.get_section_by_name(name) for name in names]
    return max((sec['sh_addr'] + sec['sh_size'] for sec in secs if sec is not None), default=0)


def _exported_symbols(elf):
    """Global functions/objects the base stub defines itself (not ROM ABS symbols)."""
    symtab = elf.get_section_by_name('.symtab')
    if symtab is None:
        sys.exit('ERROR: base stub ELF has no symbol table')
    return {
        sym.name: sym['st_value']
        for sym in symtab.iter_symbols()
        if sym['st_info']['bind'] == 'STB_GLOBAL'
        and sym['st_info']['type'] in ('STT_FUNC', 'STT_OBJECT')
        and isinstance(sym['st_shndx'], int)
    }


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument('base_stub_elf', help='Path to the base stub ELF file')
    parser.add_argument('output_ld', help='Path to the linker fragment to write')
    parser.add_argument(
        '--after',
        action='append',
        default=[],
        metavar='PLUGIN_ELF',
        help='ELF of a plugin loaded before this one; repeat in load order to stack.',
    )
    args = parser.parse_args()

    # The plugin goes after the base stub and after each preceding plugin.
    text_end = dram_end = 0
    for path in [args.base_stub_elf, *args.after]:
        with open(path, 'rb') as f:
            elf = ELFFile(f)
            text_end = max(text_end, _end(elf, '.text'))
            dram_end = max(dram_end, _end(elf, '.bss', '.data'))
            if path == args.base_stub_elf:
                if not text_end or not dram_end:
                    sys.exit(f'ERROR: no .text, .data or .bss in base stub ELF {path}')
                exports = _exported_symbols(elf)

    text_addr = align_up(text_end, 16)
    bss_addr = align_up(dram_end, 4)

    with open(args.output_ld, 'w') as out:
        out.write('/* Auto-generated by compute_plugin_addrs.py — do not edit */\n')
        out.write(f'PLUGIN_TEXT_ADDR = 0x{text_addr:08X};\n')
        out.write(f'PLUGIN_BSS_ADDR  = 0x{bss_addr:08X};\n')
        # PROVIDE only defines names the plugin uses but does not define itself,
        # so the plugin's own copy of esp-stub-lib still takes precedence.
        for name, addr in sorted(exports.items()):
            out.write(f'PROVIDE({name} = 0x{addr:08X});\n')


if __name__ == '__main__':
    main()
